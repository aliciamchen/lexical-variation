"""
Statistics as LaTeX macros.

Numbers reach the manuscript only as `\\newcommand` macros in the files of
results/<dataset>/stats/, which `make sync` copies into the Overleaf project
where main.tex reads them with `\\input`. Two writers produce them:
paper/inferential.py formats the model estimates (checks, primary and
secondary) and paper/descriptives.py the descriptive statistics (overview,
exploratory and survey). Both use this module, so every file has the same
header (the writer, then the git commit and dataset it was written from), the
same line format, the same rule that a macro name is letters only (so
`\\primaryNGames` is fine and `\\primaryN2` is not) and the same refusal of
duplicate names. `check_unique_names()` reads every file in a stats
directory, whoever wrote it, and reports a name defined in more than one
file, because main.tex reads all of them together.

Usage:
    from paper.stats_tex import fmt_stat, stats_file, write_stats_tex
    macros = {"overviewNGames": 120, "overviewAccuracy": fmt_stat(0.8123)}
    write_stats_tex(macros, stats_file("overview", dirs), source="paper/descriptives.py", dataset=dirs.name)

Tests: paper/test_stats_tex.py
"""

from __future__ import annotations

import math
import re
from collections.abc import Mapping
from pathlib import Path

from pipeline.dataset_paths import dataset_dirs
from pipeline.provenance import git_commit

NAME_PATTERN = re.compile(r"^[A-Za-z]+$")
MACRO_PATTERN = re.compile(r"\\newcommand\{\\([A-Za-z]+)\}")


def stats_file(name: str, dirs=None) -> Path:
    """Where a stats file goes: results/<dataset>/stats/<name>.tex.

    The stem is the file's macro prefix, letters only, so the file name and
    the macro names agree. `dirs` is the dataset's DatasetDirs; the active
    dataset when omitted.
    """
    if not NAME_PATTERN.match(name):
        raise ValueError(f"a stats file stem is letters only, not {name!r}")
    return (dirs or dataset_dirs()).stats / f"{name}.tex"


def _is_missing(x) -> bool:
    if x is None:
        return True
    try:
        return isinstance(x, float) and math.isnan(x)
    except TypeError:
        return False


def write_stats_tex(
    macros: Mapping[str, object],
    path: Path | str,
    source: str = "an analysis script",
    dataset: str | None = None,
) -> Path:
    """Write `macros` as \\newcommand lines under the AUTO-GENERATED header.

    Every name must be letters only and appear once; a missing value (None or
    NaN) is written as an empty macro. The second header line records the git
    commit of the working tree and, when given, the dataset.
    """
    names = list(macros)
    bad = [n for n in names if not isinstance(n, str) or not NAME_PATTERN.match(n)]
    if bad:
        raise ValueError(f"LaTeX command names may contain letters only: {', '.join(map(str, bad))}")
    seen, dup = set(), []
    for n in names:
        if n in seen and n not in dup:
            dup.append(n)
        seen.add(n)
    if dup:
        raise ValueError(f"duplicate macro names: {', '.join(dup)}")
    provenance = f"% commit {git_commit()}" + (f", dataset {dataset}" if dataset else "")
    lines = [f"% AUTO-GENERATED by {source} -- do not edit by hand.", provenance]
    for name in names:
        value = macros[name]
        text = "" if _is_missing(value) else str(value)
        lines.append(f"\\newcommand{{\\{name}}}{{{text}}}")
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    print(f"Wrote {len(names)} macros to {path}")
    return path


def stats_tex_names(path: Path | str) -> list[str]:
    """The macro names a stats file defines, in file order."""
    return MACRO_PATTERN.findall(Path(path).read_text())


def check_unique_names(stats_dir: Path | str | None = None) -> dict[str, list[str]]:
    """Macro names defined in more than one file of a stats directory.

    Returns {name: [file, ...]} for every name that appears in two or more
    files; empty when the files can be \\input together. The active dataset's
    directory when none is given.
    """
    stats_dir = Path(stats_dir) if stats_dir is not None else dataset_dirs().stats
    where: dict[str, list[str]] = {}
    for path in sorted(stats_dir.glob("*.tex")):
        for name in stats_tex_names(path):
            where.setdefault(name, []).append(path.name)
    return {name: files for name, files in where.items() if len(files) > 1}


# ── Formatting ───────────────────────────────────────────────
# The manuscript's conventions for a number, in one place.


def fmt_stat(x, digits: int = 3) -> str:
    """A statistic to a fixed number of decimals; "NA" when missing."""
    if _is_missing(x):
        return "NA"
    return f"{float(x):.{digits}f}"


def fmt_count(n) -> str:
    """A count with the LaTeX-safe thousands separator: 1234 -> 1{,}234."""
    if _is_missing(n):
        return "NA"
    return f"{int(round(float(n))):,}".replace(",", "{,}")


def fmt_pval(p) -> str:
    """A p-value as the manuscript prints it: "< .001", or three decimals with no leading zero."""
    if _is_missing(p):
        return "NA"
    p = float(p)
    if p < 0.001:
        return "< .001"
    text = f"{p:.3f}"
    return text[1:] if text.startswith("0") else text


def fmt_bf(bf10) -> str:
    """A Bayes factor to two significant digits with no padding: 0.052, 0.18, 1.0, 3.2, 12."""
    if _is_missing(bf10):
        return "NA"
    x = float(f"{float(bf10):.2g}")
    if x >= 10:
        return f"{x:.0f}"
    if x >= 1:
        return f"{x:.1f}"
    if x >= 0.1:
        return f"{x:.2f}"
    if x >= 0.01:
        return f"{x:.3f}"
    return f"{x:.2g}"


def condition_macro_name(condition: str) -> str:
    """A condition id as the CamelCase fragment of a macro name: refer_separated -> ReferSeparated."""
    return "".join(part[:1].upper() + part[1:] for part in str(condition).split("_"))
