"""
Tests for the Python macro writer (analysis/stats_tex.py): the file format the
R writer produces, the name rules, the formatting helpers, and the check that
no macro is defined in two stats files.

Run with:
    uv run pytest analysis/test_stats_tex.py -v
"""

import math

import pytest

from stats_tex import (
    STATS_DIR,
    check_unique_names,
    condition_macro_name,
    fmt_count,
    fmt_pval,
    fmt_stat,
    stats_file,
    stats_tex_names,
    write_stats_tex,
)


def test_write_stats_tex_matches_the_r_writers_format(tmp_path):
    path = tmp_path / "descriptive.tex"
    write_stats_tex(
        {"descriptiveNGames": 120, "descriptiveAccuracy": fmt_stat(0.81234), "descriptiveNote": None},
        path,
        source="analysis/descriptives.py",
    )
    assert path.read_text() == (
        "% AUTO-GENERATED by analysis/descriptives.py -- do not edit by hand.\n"
        "\\newcommand{\\descriptiveNGames}{120}\n"
        "\\newcommand{\\descriptiveAccuracy}{0.812}\n"
        "\\newcommand{\\descriptiveNote}{}\n"
    )
    assert stats_tex_names(path) == ["descriptiveNGames", "descriptiveAccuracy", "descriptiveNote"]


def test_names_are_letters_only(tmp_path):
    with pytest.raises(ValueError, match="letters only"):
        write_stats_tex({"descriptiveN2": 1}, tmp_path / "x.tex")
    with pytest.raises(ValueError, match="letters only"):
        write_stats_tex({"descriptive_n": 1}, tmp_path / "x.tex")
    with pytest.raises(ValueError, match="letters only"):
        stats_file("descriptive2")
    assert stats_file("descriptive") == STATS_DIR / "descriptive.tex"


def test_missing_values_become_empty_macros(tmp_path):
    path = write_stats_tex({"a": float("nan"), "b": None, "c": 0}, tmp_path / "x.tex")
    lines = path.read_text().splitlines()[1:]
    assert lines == ["\\newcommand{\\a}{}", "\\newcommand{\\b}{}", "\\newcommand{\\c}{0}"]


def test_formatting_helpers_follow_the_r_rules():
    assert fmt_stat(1.23456) == "1.235"
    assert fmt_stat(-0.0004) == "-0.000"
    assert fmt_stat(2, digits=1) == "2.0"
    assert fmt_stat(None) == "NA" and fmt_stat(math.nan) == "NA"
    assert fmt_count(1234567) == "1{,}234{,}567"
    assert fmt_count(12.4) == "12" and fmt_count(None) == "NA"
    assert fmt_pval(0.0004) == "< .001"
    assert fmt_pval(0.0423) == ".042"
    assert fmt_pval(1) == "1.000"
    assert fmt_pval(float("nan")) == "NA"
    assert condition_macro_name("refer_separated") == "ReferSeparated"
    assert condition_macro_name("social_first") == "SocialFirst"


def test_duplicate_names_are_found_across_files(tmp_path):
    write_stats_tex({"nGames": 1, "onlyHere": 2}, tmp_path / "a.tex")
    write_stats_tex({"nGames": 1, "elsewhere": 3}, tmp_path / "b.tex")
    write_stats_tex({"third": 4}, tmp_path / "c.tex")
    assert check_unique_names(tmp_path) == {"nGames": ["a.tex", "b.tex"]}


def test_the_manuscripts_stats_files_define_each_macro_once():
    """The six files are \\input together, so a name defined twice is an error
    whichever writers produced it. Skipped where the manuscript project is
    absent (a clone without writing/)."""
    if not STATS_DIR.is_dir() or not any(STATS_DIR.glob("*.tex")):
        pytest.skip("no manuscript stats directory in this checkout")
    assert check_unique_names(STATS_DIR) == {}
