"""
Statistics as LaTeX macros, for the Python side of the article.

Numbers reach the manuscript only as `\\newcommand` macros in a stats/*.tex file
that main.tex reads with `\\input`. The R notebooks write the inferential files
with `write_stats_tex()` in analysis/R/stats_tex.R; this module is its twin for
the descriptive statistics Python computes beside the figures, with the same
header, the same line format, the same rule that a macro name is letters only
(so `\\primaryNGames` is fine and `\\primaryN2` is not) and the same refusal of
duplicate names. `check_unique_names()` reads every file in the stats
directory, whoever wrote it, and reports a name defined in more than one file,
because main.tex reads all of them together.

Usage:
    from stats_tex import fmt_stat, stats_file, write_stats_tex
    macros = {"descriptiveNGames": 120, "descriptiveAccuracy": fmt_stat(0.8123)}
    write_stats_tex(macros, stats_file("descriptive"), source="analysis/descriptives.py")

Tests: analysis/test_stats_tex.py
"""

from __future__ import annotations

import math
import re
from collections.abc import Mapping
from pathlib import Path

from dataset_paths import PROJECT_ROOT

STATS_DIR = PROJECT_ROOT / "writing" / "manuscript" / "stats"

NAME_PATTERN = re.compile(r"^[A-Za-z]+$")
MACRO_PATTERN = re.compile(r"\\newcommand\{\\([A-Za-z]+)\}")


def stats_file(name: str) -> Path:
    """Where a stats file goes: writing/manuscript/stats/<name>.tex.

    The stem is the file's macro prefix, letters only, so the file name and
    the macro names agree.
    """
    if not NAME_PATTERN.match(name):
        raise ValueError(f"a stats file stem is letters only, not {name!r}")
    return STATS_DIR / f"{name}.tex"


def _is_missing(x) -> bool:
    if x is None:
        return True
    try:
        return isinstance(x, float) and math.isnan(x)
    except TypeError:
        return False


def write_stats_tex(macros: Mapping[str, object], path: Path | str, source: str = "an analysis script") -> Path:
    """Write `macros` as \\newcommand lines under an AUTO-GENERATED header.

    Every name must be letters only and appear once; a missing value (None or
    NaN) is written as an empty macro, as in R, where a NULL value becomes "".
    """
    names = list(macros)
    bad = [n for n in names if not isinstance(n, str) or not NAME_PATTERN.match(n)]
    if bad:
        raise ValueError(f"LaTeX command names may contain letters only: {', '.join(map(str, bad))}")
    seen, dup = set(), []
    for n in names:
        if n in seen and n not in dup:
            dup.append(n)
        seen.add(n)
    if dup:
        raise ValueError(f"duplicate macro names: {', '.join(dup)}")
    lines = [f"% AUTO-GENERATED by {source} -- do not edit by hand."]
    for name in names:
        value = macros[name]
        text = "" if _is_missing(value) else str(value)
        lines.append(f"\\newcommand{{\\{name}}}{{{text}}}")
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    print(f"Wrote {len(names)} macros to {path}")
    return path


def stats_tex_names(path: Path | str) -> list[str]:
    """The macro names a stats file defines, in file order."""
    return MACRO_PATTERN.findall(Path(path).read_text())


def check_unique_names(stats_dir: Path | str = STATS_DIR) -> dict[str, list[str]]:
    """Macro names defined in more than one file of the stats directory.

    Returns {name: [file, ...]} for every name that appears in two or more
    files; empty when the files can be \\input together.
    """
    stats_dir = Path(stats_dir)
    where: dict[str, list[str]] = {}
    for path in sorted(stats_dir.glob("*.tex")):
        for name in stats_tex_names(path):
            where.setdefault(name, []).append(path.name)
    return {name: files for name, files in where.items() if len(files) > 1}


# ── Formatting ───────────────────────────────────────────────
# The same rules as the R helpers, so a number reads the same whichever side
# wrote it.


def fmt_stat(x, digits: int = 3) -> str:
    """A statistic to a fixed number of decimals; "NA" when missing."""
    if _is_missing(x):
        return "NA"
    return f"{float(x):.{digits}f}"


def fmt_count(n) -> str:
    """A count with the LaTeX-safe thousands separator: 1234 -> 1{,}234."""
    if _is_missing(n):
        return "NA"
    return f"{int(round(float(n))):,}".replace(",", "{,}")


def fmt_pval(p) -> str:
    """A p-value as the manuscript prints it: "< .001", or three decimals with no leading zero."""
    if _is_missing(p):
        return "NA"
    p = float(p)
    if p < 0.001:
        return "< .001"
    text = f"{p:.3f}"
    return text[1:] if text.startswith("0") else text


def condition_macro_name(condition: str) -> str:
    """A condition id as the CamelCase fragment of a macro name: refer_separated -> ReferSeparated."""
    return "".join(part[:1].upper() + part[1:] for part in str(condition).split("_"))
