"""
Tests for the macro writer (report/stats_tex.py): the file format, the name
rules, the formatting helpers, and the check that no macro is defined in two
stats files.

Run with:
    uv run pytest report/test_stats_tex.py -v
"""

import math
import re

import pytest

from preprocessing.dataset_paths import dataset_dirs
from report.stats_tex import (
    check_unique_names,
    condition_macro_name,
    fmt_bf,
    fmt_count,
    fmt_pval,
    fmt_stat,
    stats_file,
    stats_tex_names,
    write_stats_tex,
)


def test_write_stats_tex_writes_the_header_the_provenance_and_the_macros(tmp_path):
    path = tmp_path / "overview.tex"
    write_stats_tex(
        {"overviewNGames": 120, "overviewAccuracy": fmt_stat(0.81234), "overviewNote": None},
        path,
        source="report/descriptives.py",
        dataset="full",
    )
    lines = path.read_text().splitlines()
    assert lines[0] == "% AUTO-GENERATED by report/descriptives.py -- do not edit by hand."
    assert re.fullmatch(r"% commit ([0-9a-f]{7,}(-dirty)?|unknown), dataset full", lines[1])
    assert lines[2:] == [
        "\\newcommand{\\overviewNGames}{120}",
        "\\newcommand{\\overviewAccuracy}{0.812}",
        "\\newcommand{\\overviewNote}{}",
    ]
    assert stats_tex_names(path) == ["overviewNGames", "overviewAccuracy", "overviewNote"]


def test_names_are_letters_only(tmp_path):
    with pytest.raises(ValueError, match="letters only"):
        write_stats_tex({"overviewN2": 1}, tmp_path / "x.tex")
    with pytest.raises(ValueError, match="letters only"):
        write_stats_tex({"overview_n": 1}, tmp_path / "x.tex")
    with pytest.raises(ValueError, match="letters only"):
        stats_file("overview2")
    dirs = dataset_dirs("smoke")
    assert stats_file("overview", dirs) == dirs.macros / "overview.tex"
    assert stats_file("overview").parent == dataset_dirs().macros


def test_missing_values_become_empty_macros(tmp_path):
    path = write_stats_tex({"a": float("nan"), "b": None, "c": 0}, tmp_path / "x.tex")
    lines = path.read_text().splitlines()[2:]
    assert lines == ["\\newcommand{\\a}{}", "\\newcommand{\\b}{}", "\\newcommand{\\c}{0}"]


def test_formatting_helpers():
    assert fmt_stat(1.23456) == "1.235"
    assert fmt_stat(-0.0004) == "-0.000"
    assert fmt_stat(2, digits=1) == "2.0"
    assert fmt_stat(None) == "NA" and fmt_stat(math.nan) == "NA"
    assert fmt_count(1234567) == "1{,}234{,}567"
    assert fmt_count(12.4) == "12" and fmt_count(None) == "NA"
    assert fmt_pval(0.0004) == "< .001"
    assert fmt_pval(0.0423) == ".042"
    assert fmt_pval(1) == "1.000"
    assert fmt_pval(float("nan")) == "NA"
    assert condition_macro_name("refer_separated") == "ReferSeparated"
    assert condition_macro_name("social_first") == "SocialFirst"


def test_bayes_factors_have_two_significant_digits_and_no_padding():
    assert fmt_bf(1) == "1.0" and fmt_bf(1.0004) == "1.0"
    assert fmt_bf(0.177) == "0.18"
    assert fmt_bf(12.3) == "12"
    assert fmt_bf(0.0523) == "0.052"
    assert fmt_bf(3.14) == "3.1"
    assert fmt_bf(0.2531) == "0.25"
    assert fmt_bf(2.6e-07) == "2.6e-07" and fmt_bf(0.0003) == "0.0003"
    assert fmt_bf(None) == "NA"
    assert " " not in fmt_bf(1.0004)


def test_duplicate_names_are_found_across_files(tmp_path):
    write_stats_tex({"nGames": 1, "onlyHere": 2}, tmp_path / "a.tex")
    write_stats_tex({"nGames": 1, "elsewhere": 3}, tmp_path / "b.tex")
    write_stats_tex({"third": 4}, tmp_path / "c.tex")
    assert check_unique_names(tmp_path) == {"nGames": ["a.tex", "b.tex"]}


def test_the_results_stats_files_define_each_macro_once():
    """The six files are \\input together, so a name defined twice is an error
    whichever writer produced it. Skipped where the results tree is absent."""
    stats_dir = dataset_dirs().macros
    if not stats_dir.is_dir() or not any(stats_dir.glob("*.tex")):
        pytest.skip("no stats directory for the active dataset in this checkout")
    assert check_unique_names(stats_dir) == {}
